"""Paths and settings. Everything can be overridden with environment variables."""
import os
from pathlib import Path

ROOT = Path(os.environ.get("TRUEMENU_ROOT", Path(__file__).resolve().parent.parent))
DATA_DIR = ROOT / "data"
STATE_DIR = Path(os.environ.get("TRUEMENU_STATE", ROOT / "state"))
STATE_DIR.mkdir(parents=True, exist_ok=True)

DB_PATH = STATE_DIR / "truemenu.db"
GROUND_TRUTH = DATA_DIR / "ground_truth.csv"
MERCHANTS = DATA_DIR / "merchants.json"
OVERRIDES = STATE_DIR / "overrides.json"      # demo-time changes the simulated POS applies
FEED_PID = STATE_DIR / "feed.pid"

# Secret for signing quotes. Generated by setup.sh into .env; never commit it.
QUOTE_SECRET = os.environ.get("TRUEMENU_QUOTE_SECRET", "")
QUOTE_TTL_S = int(os.environ.get("TRUEMENU_QUOTE_TTL_S", "900"))

# A tag is trusted for filtering only at or above this confidence.
SERVING_THRESHOLD = float(os.environ.get("TRUEMENU_SERVING_THRESHOLD", "0.6"))

# Optional override of every source's sync interval (handy for recording the demo).
SYNC_INTERVAL_OVERRIDE = os.environ.get("TRUEMENU_SYNC_INTERVAL_S")

# Agent keys: "name:key:scope1+scope2,name2:key2:scope". Set by setup.sh.
def agent_keys():
    raw = os.environ.get("TRUEMENU_AGENT_KEYS", "")
    out = {}
    for part in filter(None, (p.strip() for p in raw.split(","))):
        name, key, scopes = part.split(":", 2)
        out[key] = {"agent": name, "scopes": set(scopes.split("+"))}
    return out

SERVICE_URL = os.environ.get("TRUEMENU_URL", "http://127.0.0.1:8088")
VERSION = "0.1.0"
